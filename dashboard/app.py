#  PSFAnalyzer
# ──────────────────────────────────────────────────────────────────────────────


class PSFAnalyzer:
    """Loads the model and runs per-image analysis."""

    def __init__(self, ckpt_path: str, config_path: str):
        self.dev      = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        self.cfg      = load_config(config_path)
        self.model    = build_model(self.cfg).to(self.dev)
        self.load_weights(ckpt_path)
        self.img_size  = self.cfg["data"].get("img_size", 518)
        self.transform = get_transforms(img_size=self.img_size, is_train=False)
        self.rollout   = ViTAttentionRollout(self.model)
        self.label_cols = self.cfg["data"].get("label_cols", ["Creativity", "Belonging", "EaseOfUse"])

    def load_weights(self, ckpt_path: str) -> str:
        try:
            checkpoint = torch.load(ckpt_path, map_location=self.dev)
            self.model.load_state_dict(checkpoint["model_state_dict"])
            self.model.eval()
            return f"✓ Loaded: {Path(ckpt_path).name}"
        except Exception as e:
            return f"✗ Error loading checkpoint: {e}"

    def analyze(self, input_img: np.ndarray):
        """Run model inference + attention rollout on a single image."""
        if input_img is None:
            return None, {}
        raw_img = Image.fromarray(input_img).convert("RGB")
        img_t   = self.transform(raw_img).unsqueeze(0).to(self.dev)

        with torch.no_grad():
            preds = self.model(img_t).cpu().numpy()[0]

        mask        = self.rollout(img_t)
        heatmap_img = overlay_heatmap(raw_img, mask)

        return (
            heatmap_img,
            round(float(preds[0]), 2),   # Creativity
            round(float(preds[1]), 2),   # Belonging
            round(float(preds[2]), 2),   # EaseOfUse
        )


# ──────────────────────────────────────────────────────────────────────────────
#  Plotly radar chart
# ──────────────────────────────────────────────────────────────────────────────


def create_interactive_radar(scores: list, labels: list) -> go.Figure:
    """Build an interactive Plotly polar/radar chart for PSF scores."""
    def get_color(x):
        if   x < 2.7:  return "#ef4444"   # red   — Low
        elif x < 3.3:  return "#f59e0b"   # amber — Moderate
        elif x <= 4.0: return "#10b981"   # green — Good
        else:          return "#3b82f6"   # blue  — Excellent

    marker_colors = [get_color(s) for s in scores]
    marker_colors.append(marker_colors[0])  # close the radar loop

    fig = go.Figure()
    fig.add_trace(go.Scatterpolar(
        r=scores + [scores[0]],
        theta=labels + [labels[0]],
        fill="toself",
        fillcolor="rgba(220, 38, 38, 0.15)",
        line=dict(color="#dc2626", width=3),
        marker=dict(color=marker_colors, size=16, symbol="circle",
                    line=dict(color="white", width=2)),
        name="AI Perception Rating",
        hoverinfo="r+theta",
    ))
    fig.update_layout(
        polar=dict(
            radialaxis=dict(
                visible=True, range=[0, 5],
                tickvals=[1, 2, 3, 4, 5],
                gridcolor="#E5E7EB",
            ),
            angularaxis=dict(gridcolor="#E5E7EB", linecolor="#9CA3AF"),
            bgcolor="white",
        ),
        showlegend=False,
        margin=dict(l=40, r=40, t=20, b=20),
        paper_bgcolor="white",
        plot_bgcolor="white",
    )
    return fig


